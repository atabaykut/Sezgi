use super::*;

#[test]
fn rfc8785_sayilar() {
    // RFC 8785 ve ECMAScript örnekleri
    for (f, beklenen) in [
        (0.0, "0"),
        (-0.0, "0"),
        (1.0, "1"),
        (4.5, "4.5"),
        (0.002, "0.002"),
        (0.000001, "0.000001"),
        (1e-7, "1e-7"),
        (1e21, "1e+21"),
        (1e20, "100000000000000000000"),
        (1e30, "1e+30"),
        (333333333.3333333, "333333333.3333333"),
        (-1.5e-9, "-1.5e-9"),
        (5e-324, "5e-324"),
        (1.7976931348623157e308, "1.7976931348623157e+308"),
        (9007199254740992.0, "9007199254740992"),
        (295147905179352830000.0, "295147905179352830000"),
    ] {
        assert_eq!(es_sayi(f), beklenen, "{f}");
    }
}

#[test]
fn rfc8785_nesne() {
    // Anahtar sırası UTF-16'ya göre: U+20AC < U+1F600 (vekil çift D83D) < U+FB33
    let v = json!({ "b": [1.0, { "z": 0.5, "a": "\u{7}é" }], "a": -0.0, "\u{20ac}": 1, "\u{1f600}": 2, "\u{fb33}": 3 });
    let beklenen = "{\"a\":0,\"b\":[1,{\"a\":\"\\u0007é\",\"z\":0.5}],\"\u{20ac}\":1,\"\u{1f600}\":2,\"\u{fb33}\":3}";
    assert_eq!(kanonik(&v), beklenen);
}
